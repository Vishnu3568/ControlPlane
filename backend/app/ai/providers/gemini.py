import httpx
import logging
from typing import List, Dict, Any, Optional
from backend.app.ai.providers.base import BaseAIProvider
from backend.app.core.config import settings

logger = logging.getLogger(__name__)

class GeminiProvider(BaseAIProvider):
    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model = model or settings.GEMINI_MODEL or "gemini-2.5-flash"

    async def generate_reply(
        self,
        prompt: str,
        system_instruction: str,
        history: Optional[List[Dict[str, str]]] = None
    ) -> str:
        if not self.api_key or self.api_key.strip() == "":
            return self._offline_mentor_reply(prompt, system_instruction)

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        # Construct contents array with history
        contents = []
        if history:
            for msg in history:
                role = "user" if msg.get("role") == "user" else "model"
                contents.append({
                    "role": role,
                    "parts": [{"text": msg.get("content", "")}]
                })
        
        contents.append({
            "role": "user",
            "parts": [{"text": prompt}]
        })

        payload = {
            "system_instruction": {
                "parts": [{"text": system_instruction}]
            },
            "contents": contents,
            "generationConfig": {
                "temperature": 0.3,
                "maxOutputTokens": 2048,
            }
        }

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                res = await client.post(url, json=payload)
                if res.status_code == 200:
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if candidates and "content" in candidates[0]:
                        parts = candidates[0]["content"].get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
                    return "No response content generated by Gemini."
                else:
                    logger.warning(f"Gemini API returned status {res.status_code}: {res.text}")
                    return f"[AI Provider Error - Status {res.status_code}]: {res.text}"
        except Exception as e:
            logger.error(f"Error calling Gemini API: {str(e)}")
            return self._offline_mentor_reply(prompt, system_instruction, error=str(e))

    def _offline_mentor_reply(self, prompt: str, system_instruction: str, error: Optional[str] = None) -> str:
        prefix = f"(Offline Mode Active - Note: {error})\n\n" if error else "(Offline Mode Active - No API Key set in .env)\n\n"
        
        # Smart offline Socratic responses
        p_lower = prompt.lower()
        if "weakness" in p_lower or "study" in p_lower:
            return (
                f"{prefix}### Mentor Assessment:\n"
                "To identify your current technical weaknesses, look at your Learning Center:\n"
                "1. Topics marked `Learning` or `Revision Required` with 0 logged assessments are your highest risk areas.\n"
                "2. When studying Operating Systems or Distributed Systems, prioritize fundamental memory models and concurrency primitives before advanced frameworks.\n"
                "3. Recommendation: Start a 30-minute focus session on your highest priority subject right now."
            )
        elif "project" in p_lower or "architecture" in p_lower or "billing" in p_lower:
            return (
                f"{prefix}### Technical Architecture Review:\n"
                "Reviewing your local engineering rules:\n"
                "1. Maintain thin API routes and isolate business transactions in service layers.\n"
                "2. Never use MongoDB schema-less design as an excuse for poor data contracts—enforce Pydantic validation on all models.\n"
                "3. Log every significant tradeoff as an ADR (Architecture Decision Record) in your Project Intelligence tab."
            )
        elif "business" in p_lower or "idea" in p_lower:
            return (
                f"{prefix}### Socratic Business Challenge:\n"
                "Before writing code for any business opportunity:\n"
                "1. Who is the specific buyer who will pay money for this?\n"
                "2. What is the manual workaround they use today, and why is it painful?\n"
                "3. Run an experiment in your Business Lab: schedule 5 customer discovery interviews before building features."
            )
        else:
            return (
                f"{prefix}### Strict Engineering Mentor:\n"
                f"You asked: *\"{prompt}\"*\n\n"
                "Core Rule: As an aspiring independent software engineer and founder, always test assumptions with real code and evidence.\n"
                "- If this is an academic concept, state the fundamental invariant first.\n"
                "- If this is a bug, isolate the minimal reproducible failure in a test.\n"
                "- If this is a product idea, validate customer willingness to pay before building."
            )

